/** numpy wraps scalars as np.float64(…); the sandbox echoes the bare number */
const norm = (s: string) => s.replace(/np\.(?:float64|int64|bool)\(([^)]*)\)/g, '$1').replace(/\s+/g, ' ').trim()

describe('np.matrix and the inverse trig functions match NumPy', () => {
  for (const [code, want] of CASES) {
    it(code.replace(/\n/g, ' ; '), () => {
      const lines = code.split('\n')
      const last = lines.pop()!
      const src = `${SETUP}${lines.join('\n')}\n${last.startsWith('print') ? last : `__r = ${last}\nprint(repr(__r))`}\n`
      const r = runPython(src)
      const got = r.error ? `${r.error.type}: ${r.error.message}` : r.stdout.trim()
      expect(norm(got)).toBe(norm(want))
    })
  }
})
